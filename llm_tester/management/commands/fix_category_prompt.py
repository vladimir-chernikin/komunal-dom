#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Management команда для обновления промпта filter-category с цепочкой рассуждений

ИСПОЛЬЗОВАНИЕ:
    python manage.py fix_category_prompt

ИЗМЕНЕНИЯ:
- Заменены заглушки на полную цепочку рассуждений
- Добавлен анализ ключевых слов для каждой категории
- Добавлено взвешивание (OBJ * EVENT * PLACE)
"""

from django.core.management.base import BaseCommand
from llm_tester.models import PromptTemplate


class Command(BaseCommand):
    help = 'Обновляет промпт filter-category с цепочкой рассуждений'

    def handle(self, *args, **options):
        # Полный промпт для category с цепочкой рассуждений
        category_template = """## Роль
Ты — строгий алгоритмический классификатор категории проблемы. Выполняй ТОЛЬКО алгоритм. Выход ТОЛЬКО JSON.

## Входные данные
TXT_PRB = "{txtPrb}"
CATEGORIES = [{categories_str}]

## АЛГОРИТМ (СТРОГО ПО ШАГАМ, ПРИСВАИВАЙ ПЕРЕМЕННЫЕ!)

### Шаг1. Сущности
OBJ = "[сущность-проблема]"
EVENT = "[событие/действие]"
PLACE = "[место]"
reasoning_txt = "Шаг1: OBJ=" + OBJ + "; EVENT=" + EVENT + "; PLACE=" + PLACE

### Шаг2. Анализ OBJ (сущность-проблема)
M_OBJ = {cat: 0.0 for cat in CATEGORIES}

# 2.1 Водоснабжение (ключи: вод(а/ы), кран, смеситель, труба холодн, протечк/капает/течет, засор(трубы))
obj_lower = OBJ.lower()
если ANY(ключ in obj_lower для ключ из ["вод", "кран", "смеситель", "протечк", "капает", "течет"]):
    M_OBJ["Водоснабжение"] += 0.7
    reasoning_txt += " | 2.1: OBJ содержит '" + ключ + "' → Водоснабжение+0.7"

# 2.2 Канализация (ключи: канализ, засор, унитаз, раковин, слив, запах(канал), труба сточн)
если ANY(ключ in obj_lower для ключ из ["канализ", "засор", "унитаз", "раковин", "слив", "туалет"]):
    M_OBJ["Канализация"] += 0.7
    reasoning_txt += " | 2.2: OBJ содержит '" + ключ + "' → Канализация+0.7"

# 2.3 Отопление (ключи: батарей, радиатор, отоплен, тепл, труба горяч, не греет, холодн(бат))
если ANY(ключ in obj_lower для ключ из ["батарей", "радиатор", "отоплен", "тепл", "не греет"]):
    M_OBJ["Отопление"] += 0.7
    reasoning_txt += " | 2.3: OBJ содержит '" + ключ + "' → Отопление+0.7"

# 2.4 Электричество (ключи: электрич, свет, розетк, выключател, провод, лампочк, fuse, предохранител, не работает(свет))
если ANY(ключ in obj_lower для ключ из ["электрич", "свет", "розетк", "выключател", "лампочк", "не работает"]):
    M_OBJ["Электричество"] += 0.7
    reasoning_txt += " | 2.4: OBJ содержит '" + ключ + "' → Электричество+0.7"

# 2.5 Газоснабжение (ключи: газ, плит(а), запах(газ), труба газов, колонк)
если ANY(ключ in obj_lower для ключ из ["газ", "газов", "колонк", "плит"]):
    M_OBJ["Газоснабжение"] += 0.8
    reasoning_txt += " | 2.5: OBJ содержит '" + ключ + "' → Газоснабжение+0.8"

# 2.6 Лифты (ключи: лифт, кабин, застрял, не ездит, кнопк(лифт))
если ANY(ключ in obj_lower для ключ из ["лифт", "кабин", "застрял", "не ездит"]):
    M_OBJ["Лифты"] += 0.9
    reasoning_txt += " | 2.6: OBJ содержит '" + ключ + "' → Лифты+0.9"

# 2.7 Вентиляция (ключи: вентиляци, вытяжк, плох(воздух), духот, застоял(воздух))
если ANY(ключ in obj_lower для ключ из ["вентиляци", "вытяжк", "духот", "застоял"]):
    M_OBJ["Вентиляция"] += 0.6
    reasoning_txt += " | 2.7: OBJ содержит '" + ключ + "' → Вентиляция+0.6"

# 2.8 Конструктив (ключи: стен/потолок/пол, окн, двер, крыш, фасад, фундамент, трещин, обруш)
если ANY(ключ in obj_lower для ключ из ["стен", "потолок", "пол", "окн", "двер", "крыш", "фасад", "трещин", "обруш"]):
    M_OBJ["Конструктив"] += 0.7
    reasoning_txt += " | 2.8: OBJ содержит '" + ключ + "' → Конструктив+0.7"

# 2.9 Санитария (ключи: мусор, уборк, гряз, насеком, грызун, таракан, крыс)
если ANY(ключ in obj_lower для ключ из ["мусор", "уборк", "гряз", "насеком", "грызун", "таракан", "крыс"]):
    M_OBJ["Санитария"] += 0.7
    reasoning_txt += " | 2.9: OBJ содержит '" + ключ + "' → Санитария+0.7"

# 2.10 Пожарная безопасность (ключи: пожар, alarm, огнетушит, датчик(дым/пожар), эвакуац)
если ANY(ключ in obj_lower для ключ из ["пожар", "alarm", "огнетушит", "датчик", "эвакуац"]):
    M_OBJ["Пожарная безопасность"] += 0.8
    reasoning_txt += " | 2.10: OBJ содержит '" + ключ + "' → Пожарная+0.8"

# 2.11 Ремонт МАФ и покрытий (ключи: дорожк, площадк(дворов), лавочк, покрыт(асфальт/плитк), тротуар)
если ANY(ключ in obj_lower для ключ из ["дорожк", "площадк", "лавочк", "асфальт", "тротуар", "плитк"]):
    M_OBJ["Ремонт МАФ и покрытий"] += 0.6
    reasoning_txt += " | 2.11: OBJ содержит '" + ключ + "' → Ремонт МАФ+0.6"

# 2.12 Озеленение (ключи: дерев, куст, трав, газон, посаж, срезать/спилить)
если ANY(ключ in obj_lower для ключ из ["дерев", "куст", "трав", "газон", "спил"]):
    M_OBJ["Озеленение"] += 0.7
    reasoning_txt += " | 2.12: OBJ содержит '" + ключ + "' → Озеленение+0.7"

# 2.13 Информационные запросы (ключи: вопрос, справк, документ, как(задать/узнать), узнать,告知, спросить)
если ANY(ключ in obj_lower для ключ из ["вопрос", "справк", "документ", "узнать", "спрос"]):
    M_OBJ["Информационные запросы"] += 0.5
    reasoning_txt += " | 2.13: OBJ содержит '" + ключ + "' → Инфо-запрос+0.5"

reasoning_txt += " | M_OBJ=" + str(M_OBJ)

### Шаг3. Анализ EVENT (событие/действие)
M_EVENT = {cat: 0.0 for cat in CATEGORIES}
event_lower = EVENT.lower()

# 3.1 Аварийные события (ключи: прорв, течет, капает, затоп, авария, взрыв, пожар)
если ANY(ключ in event_lower для ключ из ["прорв", "течет", "капает", "затоп", "авари", "взрыв", "пожар"]):
    M_EVENT["Водоснабжение"] += 0.3
    M_EVENT["Канализация"] += 0.3
    M_EVENT["Газоснабжение"] += 0.3
    M_EVENT["Отопление"] += 0.3
    M_EVENT["Пожарная безопасность"] += 0.4
    reasoning_txt += " | 3.1: EVENT аварийный → Водо/Канал/Газ/Отоп/Пожар+"

# 3.2 Блокирующие события (ключи: не работает, отключил, нет(свет/вод), сломался)
если ANY(ключ in event_lower для ключ из ["не работает", "отключил", "нет", "сломал"]):
    M_EVENT["Электричество"] += 0.3
    M_EVENT["Водоснабжение"] += 0.2
    M_EVENT["Отопление"] += 0.2
    reasoning_txt += " | 3.2: EVENT блокирующий → Электр/Водо/Отоп+"

# 3.3 Запросные события (ключи: спросить, узнать, как, справк, докум)
если ANY(ключ in event_lower для ключ из ["спрос", "узна", "как", "справк", "докум"]):
    M_EVENT["Информационные запросы"] += 0.5
    reasoning_txt += " | 3.3: EVENT запросный → Инфо-запрос+0.5"

reasoning_txt += " | M_EVENT=" + str(M_EVENT)

### Шаг4. Анализ PLACE (место)
M_PLACE = {cat: 0.0 for cat in CATEGORIES}
place_lower = PLACE.lower()

# 4.1 Квартира/индивидуальное (ключи: квартир, ванн, кухн, спальн, туалет, балкон)
если ANY(ключ in place_lower для ключ из ["квартир", "ванн", "кухн", "спальн", "туалет", "балкон"]):
    M_PLACE["Водоснабжение"] += 0.2
    M_PLACE["Канализация"] += 0.2
    M_PLACE["Отопление"] += 0.2
    M_PLACE["Электричество"] += 0.2
    M_PLACE["Газоснабжение"] += 0.1
    reasoning_txt += " | 4.1: PLACE индивидуальный → Водо/Канал/Отоп/Электр+"

# 4.2 Общедомовое (ключи: подъезд, лифт, подвал, крыш, чердак, двор, фасад)
если ANY(ключ in place_lower для ключ из ["подъезд", "лифт", "подвал", "крыш", "чердак", "двор", "фасад"]):
    M_PLACE["Лифты"] += 0.3
    M_PLACE["Конструктив"] += 0.3
    M_PLACE["Пожарная безопасность"] += 0.2
    reasoning_txt += " | 4.2: PLACE общедомовый → Лифт/Конструктив/Пожар+"

reasoning_txt += " | M_PLACE=" + str(M_PLACE)

### Шаг5. Итоговый расчет (взвешенная сумма)
M_CANDIDATE = {}
for cat in CATEGORIES:
    # Формула: OBJ (вес 0.6) + EVENT (вес 0.25) + PLACE (вес 0.15)
    M_CANDIDATE[cat] = round(M_OBJ[cat] * 0.6 + M_EVENT[cat] * 0.25 + M_PLACE[cat] * 0.15, 3)
reasoning_txt += " | Шаг5: M_CANDIDATE=" + str(M_CANDIDATE)

### Шаг6. Определение победителя
Z1_cat = max(M_CANDIDATE, key=M_CANDIDATE.get)
Z1 = M_CANDIDATE[Z1_cat]
total = sum(M_CANDIDATE.values())
ostatok = total - Z1
category = null
category_confidence = "0.5"

# Условие: Z1 > остаток * 0.7 (значимый отрыв)
if Z1 > ostatok * 0.7 and Z1 > 0.3:
    category = Z1_cat
    category_confidence = str(round(min(Z1, 1.0), 1))
    reasoning_txt += " | Шаг6: Z1=" + Z1_cat + "(" + str(Z1) + "), ostatok=" + str(round(ostatok, 3)) + ", Z1>ostatok*0.7=" + str(round(ostatok*0.7, 3)) + " → " + category + "(" + category_confidence + ")"
else:
    reasoning_txt += " | Шаг6: Z1=" + Z1_cat + "(" + str(Z1) + ") недостаточно (need>" + str(round(ostatok*0.7, 3)) + ") → null(0.5)"

### Шаг7. JSON
Верни JSON в формате:
{
  "category": [значение category или null],
  "confidence": [значение category_confidence],
  "reasoning": [значение reasoning_txt]
}"""

        self.stdout.write(self.style.WARNING('=== ОБНОВЛЕНИЕ ПРОМПТА filter-category ===\n'))

        tmpl = PromptTemplate.objects.filter(slug='filter-category').first()

        if tmpl:
            old_len = len(tmpl.template) if tmpl.template else 0
            tmpl.template = category_template
            tmpl.save()
            new_len = len(tmpl.template)

            self.stdout.write(self.style.SUCCESS(f'✓ Промпт обновлен (ID: {tmpl.id})'))
            self.stdout.write(f'  Было: {old_len} символов')
            self.stdout.write(f'  Стало: {new_len} символов')
            self.stdout.write(f'  Изменение: +{new_len - old_len} символов\n')
        else:
            self.stdout.write(self.style.ERROR('✗ Промпт filter-category не найден!\n'))

        self.stdout.write(self.style.SUCCESS('ГОТОВО! Промпт обновлен с цепочкой рассуждений.'))
